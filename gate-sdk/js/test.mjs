import assert from "node:assert";
import { PassportChecker, priviGate, passportFromHeaders } from "./index.mjs";
const GOOD = { verification: { valid: true, issued_score: 700, issued_grade: "B", live: { score: 720, grade: "B" } } };
let calls = 0;
const fetchImpl = async (url) => {
  calls++;
  const id = url.split("/").pop();
  if (id === "pp_boom") throw Object.assign(new Error("x"), { name: "TypeError" });
  if (id === "pp_good") return new Response(JSON.stringify(GOOD), { status: 200 });
  return new Response("{}", { status: 404 });
};
const c = new PassportChecker({ fetchImpl });
assert.equal((await c.check("pp_good")).allow, true); await c.check("pp_good"); assert.equal(calls, 1);
assert.deepEqual((await c.check("pp_missing")).reasons, ["no such passport"]);
assert.equal((await c.check("pp_boom")).allow, false);
assert.equal((await new PassportChecker({ fetchImpl, minScore: 900 }).check("pp_good")).allow, false);
assert.equal(passportFromHeaders({ authorization: "PriviPassport pp_good" }), "pp_good");
const mk = () => { const r = { headers: {}, setHeader(k, v) { this.headers[k] = v; }, end(b) { this.body = b; } }; return r; };
const gate = priviGate({ checker: c });
let nexted = false; let res = mk();
await gate({ method: "POST", url: "/mcp", headers: { "x-privi-passport": "pp_good" } }, res, () => { nexted = true; });
assert.ok(nexted);
nexted = false; res = mk();
await gate({ method: "POST", url: "/mcp", headers: {} }, res, () => { nexted = true; });
assert.equal(nexted, false); assert.equal(res.statusCode, 401);
assert.equal(JSON.parse(res.body).error, "privi_passport_required");
nexted = false; await priviGate({ checker: c, mode: "monitor" })({ method: "POST", url: "/mcp", headers: {} }, mk(), () => { nexted = true; });
assert.ok(nexted);
console.log("privi-gate js: all tests pass");
