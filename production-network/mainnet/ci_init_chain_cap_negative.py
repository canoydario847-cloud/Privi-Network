#!/usr/bin/env python3
"""Prove a REAL patched Cosmos EVM node refuses zero-supply InitChain.

Never constructs a funded genesis. Creates a throwaway local CI node home with
a deliberately EMPTY / unfunded genesis (the default generated by 'evmd init').
The node MUST refuse to start with exactly the Privi InitChainer supply error.
Any unrelated error, success, or timeout is a TEST FAILURE, not proof.

No production signer, wallet credentials, operator data, funded balances,
tokens, transactions, deployment, public RPC or production network is used.
"""
import argparse
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile

from ci_runtime_init import CID, inspect

CAP_GUARD = "Privi genesis native supply must equal exactly 1 billion PRVI"


def is_expected_failure(returncode, stdout, stderr, marker=CAP_GUARD):
    """Reject unrelated startup failures and accidental node success."""
    if returncode == 0 or not isinstance(returncode, int):
        return False
    if not isinstance(stdout, (bytes, bytearray)) or not isinstance(stderr, (bytes, bytearray)):
        return False
    # Matched reason must be exact; do not reveal log body (could contain keys).
    return marker.encode("ascii") in stdout + stderr


def hardened_local_comet_config(text):
    """For CI-only startup, enforce EVM mempool and loopback-only gossip.

    The executable requires Comet [mempool].type=app; stock evmd init may
    generate flood. Reject uncertain configuration instead of silently
    accepting a node bound to external interfaces.
    """
    if type(text) is not str:
        raise ValueError("Comet config.toml must be text")
    lines = text.splitlines(keepends=True)
    in_mempool = False
    found_mempool_type = False
    for i, line in enumerate(lines):
        stripped = line.strip()
        if stripped == "[mempool]":
            in_mempool = True
            continue
        if stripped.startswith("[") and stripped.endswith("]"):
            in_mempool = False
        if in_mempool and re.fullmatch(r'type\s*=\s*"(?:flood|app)"(?:\s*#.*)?', stripped):
            if found_mempool_type:
                raise ValueError("Duplicate Comet mempool type")
            found_mempool_type = True
            lines[i] = line.replace('"flood"', '"app"')
    if not found_mempool_type:
        raise ValueError("Expected [mempool] type=flood/app setting absent")
    output = "".join(lines)
    if 'laddr = "tcp://0.0.0.0:26656"' in output:
        output = output.replace('laddr = "tcp://0.0.0.0:26656"',
                                'laddr = "tcp://127.0.0.1:26656"', 1)
    if 'laddr = "tcp://0.0.0.0:26656"' in output:
        raise ValueError("Public Comet P2P binding not allowed")
    return output


def prove(binary):
    path = Path(binary).resolve(strict=True)
    if not path.is_file() or not os.access(path, os.X_OK):
        raise ValueError("CI candidate executable required")
    with tempfile.TemporaryDirectory(prefix="privi-ci-cap-negative-") as temporary:
        root = Path(temporary)
        home = root / "unfunded-local-only"
        env = os.environ.copy()
        env["HOME"] = str(root)
        env["DAEMON_HOME"] = str(home)
        init = subprocess.run(
            [str(path), "--home", str(home), "init", "ci-only-no-funds", "--chain-id", CID],
            env=env, stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=60
        )
        if init.returncode != 0:
            raise ValueError("Disposable candidate init failed (output redacted)")
        genesis_file = home / "config" / "genesis.json"
        if not genesis_file.is_file():
            raise ValueError("Node init produced no genesis")
        genesis = json.loads(genesis_file.read_text(encoding="utf-8"))
        errors = inspect(genesis)
        if errors:
            raise ValueError("Disposable genesis not Privi-compatible: " + "; ".join(errors))
        bank = genesis.get("app_state", {}).get("bank", {})
        if bank.get("supply", []) or bank.get("balances", []):
            raise ValueError("Negative test must use an UNFUNDED genesis only")
        if genesis.get("validators"):
            raise ValueError("Negative test cannot use real validators")

        # Strong isolation: Comet RPC/p2p endpoints explicitly disabled from
        # accepting external connections in ephemeral config.toml.
        comet_config = home / "config" / "config.toml"
        text = comet_config.read_text(encoding="utf-8")
        comet_config.write_text(hardened_local_comet_config(text), encoding="utf-8")

        # Default no-funds genesis MUST fail with CAP_GUARD from actual Go
        # application InitChainer. No other panic/error can satisfy the test.
        try:
            startup = subprocess.run(
                [str(path), "--home", str(home), "start"],
                env=env, stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=45
            )
        except subprocess.TimeoutExpired as exc:
            raise ValueError("Node did not fail startup within 45s; InitChain cap not proven") from exc
        if not is_expected_failure(startup.returncode, startup.stdout, startup.stderr):
            # Startup logs may contain temporary paths or signing-related
            # information. Expose ONLY a narrow, scrubbed error category.
            # Never publish raw stdout/stderr or the generated config.
            source = (startup.stderr + b"\n" + startup.stdout).decode("utf-8", errors="replace")
            clues = ("invalid", "error", "panic", "missing", "failed", "address",
                     "validator", "genesis", "stake", "parameter", "chain id",
                     "consensus", "bind", "cannot", "not found", "permission denied")
            candidates = [line.strip() for line in source.splitlines()
                          if any(marker in line.lower() for marker in clues)]
            note = "unclassified failure"
            for line in candidates:
                if any(secret in line.lower() for secret in
                       ("mnemonic", "private key", "seed phrase", "passphrase",
                        "recovery phrase", "password", "0x", "secret")):
                    continue
                clean = re.sub(r"/tmp/[A-Za-z0-9_./-]+", "<CI_TEMP>", line)
                clean = re.sub(r"[a-fA-F0-9]{32,}", "<REDACTED>", clean)
                clean = re.sub(r"\x1b\[[0-9;]*m", "", clean)
                note = clean[:220]
                break
            raise ValueError(
                f"Missing exact PRVI InitChainer cap error (exit {startup.returncode}); "
                f"sanitized diagnostic: {note}")
    return {
        "result": "EXPECTED_INITCHAIN_REJECTION_VERIFIED",
        "ci_chain_id": CID,
        "genesis_allocation_base_units": "0",
        "expected_production_allocation_base_units": str(10**27),
        "financial_mainnet_activated": False,
        "no_funded_genesis_created": True,
        "state_deleted": True
    }


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--binary", required=True, type=Path)
    args = p.parse_args()
    try:
        result = prove(args.binary)
    except (ValueError, TypeError, OSError, subprocess.TimeoutExpired) as exc:
        p.exit(1, "INITCHAIN HARD CAP TEST FAILED: " + str(exc) + "\n")
    print(json.dumps(result, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
