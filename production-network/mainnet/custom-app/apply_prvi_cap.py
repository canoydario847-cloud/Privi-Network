#!/usr/bin/env python3
"""Fail-closed, source-pinned *build-only* prototype wiring for PRVI cap keeper.

Clones are disposable test workspace copies of cosmos/evm v0.7.3. Never run
on an operating blockchain or production software tree. No genesis or keys
are generated by this script; no financial PRVI is created.
"""
import argparse
import hashlib
import shutil
import subprocess
from pathlib import Path

TAG = "v0.7.3"
UPSTREAM_COMMIT = "c3ae9067a7eadcdea55a5192226916deb44c71c4"

def replace_once(content, old, new, name):
    if content.count(old) != 1:
        raise ValueError("pinned upstream mismatch at %s (expected one occurrence, found %d)"
                         % (name, content.count(old)))
    return content.replace(old, new)

def apply_patch(upstream, source_repo, *, verify_git=True):
    upstream = Path(upstream).resolve(strict=True)
    source_repo = Path(source_repo).resolve(strict=True)
    if not upstream.is_dir() or upstream.name != ".upstream-capbuild":
        raise ValueError("refusing non-disposable upstream checkout")
    if verify_git:
        tag = subprocess.check_output(["git", "-C", str(upstream), "describe",
                                       "--tags", "--exact-match"], text=True).strip()
        commit = subprocess.check_output(["git", "-C", str(upstream),
                                          "rev-parse", "HEAD"], text=True).strip()
        if (tag, commit) != (TAG, UPSTREAM_COMMIT):
            raise ValueError("upstream must be exact reviewed v0.7.3 commit")
        if subprocess.check_output(["git", "-C", str(upstream), "status",
                                    "--porcelain"], text=True).strip():
            raise ValueError("upstream checkout must be clean")
    app_path = upstream / "evmd" / "app.go"
    app = app_path.read_text(encoding="utf-8")
    app = replace_once(app,
        'evmconfig "github.com/cosmos/evm/evmd/config"',
        'evmconfig "github.com/cosmos/evm/evmd/config"\n'
        '\tprvicap "github.com/cosmos/evm/evmd/prvicap"',
        "cap import")
    app = replace_once(app,
        '\tprvicap "github.com/cosmos/evm/evmd/prvicap"',
        '\tprvicap "github.com/cosmos/evm/evmd/prvicap"\n'
        '\tprvipop "github.com/cosmos/evm/evmd/prvipop"',
        "pop import")
    # Validate the EIP-155 chain identity before module/codec construction;
    # the upstream dev chain ID must never slip into a financial PRVI binary.
    app = replace_once(app,
        "\tevmChainID := cast.ToUint64(appOpts.Get(srvflags.EVMChainID))\n\tencodingConfig := evmencoding.MakeConfig(evmChainID)",
        "\tevmChainID := cast.ToUint64(appOpts.Get(srvflags.EVMChainID))\n"
        "\tif err := prvicap.ValidateEVMChainID(evmChainID); err != nil {\n"
        "\t\tpanic(fmt.Errorf(\"PRVI EIP-155 app identity rejected: %w\", err))\n"
        "\t}\n"
        "\tencodingConfig := evmencoding.MakeConfig(evmChainID)",
        "reject upstream default EVM chain ID before constructing keepers")
    app = replace_once(app,
        "\tBankKeeper            bankkeeper.Keeper",
        "\tBankKeeper            bankkeeper.Keeper\n\tPriviCapKeeper        prvicap.Keeper\n\tPriviPoPKeeper        prvipop.Keeper",
        "cap keeper field")
    app = replace_once(app,
        "\t\tauthtypes.StoreKey, banktypes.StoreKey, stakingtypes.StoreKey,",
        "\t\tauthtypes.StoreKey, banktypes.StoreKey, stakingtypes.StoreKey,\n"
        "\t\tprvicap.StoreKey,\n\t\tprvipop.StoreKey,",
        "mount dedicated merkle KV state")
    old_bank = '''\tapp.BankKeeper = bankkeeper.NewBaseKeeper(
\t\tappCodec,
\t\truntime.NewKVStoreService(keys[banktypes.StoreKey]),
\t\tapp.AccountKeeper,
\t\tevmconfig.BlockedAddresses(),
\t\tauthAddr,
\t\tlogger,
\t)
\tapp.BankKeeper = app.BankKeeper.WithObjStoreKey(oKeys[banktypes.ObjectStoreKey])'''
    new_bank = '''\t// CRITICAL: No module may receive an unrestricted bank keeper copy.
\t// There is no financial genesis, key, or issued PRVI in this build-only prototype.
\tpriviCap, capErr := prvicap.New(runtime.NewKVStoreService(keys[prvicap.StoreKey]))
\tif capErr != nil { panic(capErr) }
\tapp.PriviCapKeeper = priviCap
\t// Native PoP company/zone state is mounted to Cosmos consensus KV.
\t// Its author registry will be loaded from reviewed chain genesis.
\tpopKeeper, popErr := prvipop.NewKeeper(runtime.NewKVStoreService(keys[prvipop.StoreKey]))
\tif popErr != nil { panic(popErr) }
\tapp.PriviPoPKeeper = popKeeper
\tbaseBank := bankkeeper.NewBaseKeeper(
\t\tappCodec,
\t\truntime.NewKVStoreService(keys[banktypes.StoreKey]),
\t\tapp.AccountKeeper,
\t\tevmconfig.BlockedAddresses(),
\t\tauthAddr,
\t\tlogger,
\t)
\tbaseBank = baseBank.WithObjStoreKey(oKeys[banktypes.ObjectStoreKey])
\tapp.BankKeeper = prvicap.RestrictedBank(baseBank, app.PriviCapKeeper)'''
    app = replace_once(app, old_bank, new_bank, "apply restriction before bank injection")
    # Pinned Cosmos SDK v0.54.3 x/bank RegisterServices enforces a
    # BaseKeeper concrete type assertion for migration registration. Passing
    # our sealed *ModuleRestrictedBank panics on InitChain. Permit a narrowly
    # scoped BaseKeeper with an aprvi MintRestriction ONLY in x/bank's module
    # constructor, while all other modules and the app-facing BankKeeper
    # continue to receive the sealed direct-balance-denying interface.
    # Migration code itself still holds raw bank collection access; security
    # review and audited upgrades remain financial NO-GO requirements.
    app = replace_once(app,
        "bank.NewAppModule(appCodec, app.BankKeeper, app.AccountKeeper, nil)",
        "bank.NewAppModule(appCodec,\n"
        "\t\t\tbaseBank.WithMintCoinsRestriction(app.PriviCapKeeper.MintRestriction),\n"
        "\t\t\tapp.AccountKeeper, nil)",
        "SDK v0.54.3 bank migration needs a distinct mint-restricted BaseKeeper")
    if app.count("bank.NewAppModule(appCodec,") != 1 or app.count(
            "baseBank.WithMintCoinsRestriction(app.PriviCapKeeper.MintRestriction)") != 1:
        raise ValueError("raw bank migration exception must remain unique")
    # No other module may receive baseBank or a concrete SDK BaseKeeper.
    module_section = app[app.index("app.ModuleManager = module.NewManager("):
                         app.index("app.ModuleManager.SetOrderInitGenesis(")]
    if module_section.count("baseBank") != 1:
        raise ValueError("raw bank keeper leaked outside the one required bank migration constructor")
    old_chainer = '''\tif err := app.UpgradeKeeper.SetModuleVersionMap(ctx, app.ModuleManager.GetVersionMap()); err != nil {
\t\tpanic(err)
\t}

\treturn app.ModuleManager.InitGenesis(ctx, app.appCodec, genesisState)'''
    new_chainer = '''\t// Validate the declared genesis supply BEFORE any module initializes.
\t// The default upstream atest demo is always refused (no aprvi supply).
\t// This has no native minting, signing, or chain activation effect.
\tbankJSON, found := genesisState[banktypes.ModuleName]
\tif !found { return nil, fmt.Errorf("PRVI cap: bank genesis absent") }
\tvar bankGenesis banktypes.GenesisState
\tif err := app.appCodec.UnmarshalJSON(bankJSON, &bankGenesis); err != nil {
\t\treturn nil, fmt.Errorf("PRVI cap: invalid bank genesis: %w", err)
\t}
\tinitialPRVI := bankGenesis.Supply.AmountOf(prvicap.BaseDenom)
\tif err := prvicap.ValidateGenesisBase(initialPRVI.String()); err != nil {
\t\treturn nil, fmt.Errorf("PRVI cap declared genesis denied before module init: %w", err)
\t}
\t// PoP company/zone authors must be pinned to immutable chain genesis.
\tpopJSON, hasPoP := genesisState[prvipop.StoreKey]
\tif !hasPoP { return nil, fmt.Errorf("Privi PoP genesis: authorization registry absent") }
\tvar popGenesis struct {
\t\tChainID string `json:"chain_id"`
\t\tAuthorities []prvipop.Authority `json:"authorities"`
\t}
\tif err := json.Unmarshal(popJSON, &popGenesis); err != nil {
\t\treturn nil, fmt.Errorf("Privi PoP genesis: malformed authorization registry: %w",err)
\t}
\tif popGenesis.ChainID != ctx.ChainID() {
\t\treturn nil, fmt.Errorf("Privi PoP genesis: Cosmos chain identity mismatch")
\t}
\tif err := prvipop.ValidateGenesis(popGenesis.ChainID,popGenesis.Authorities); err != nil {
\t\treturn nil,fmt.Errorf("Privi PoP genesis: unsafe author registry before SDK InitGenesis: %w",err)
\t}
\t// Native PRVI must actually be the EVM gas and staking denomination.
\t// Do not allow a misleading genesis with capped aprvi but fees/stake in
\t// upstream stake/atest. All checks precede consensus module writes.
\tevmJSON, hasEVM := genesisState[evmtypes.ModuleName]
\tif !hasEVM { return nil, fmt.Errorf("PRVI native genesis: missing EVM module") }
\tvar evmGenesis evmtypes.GenesisState
\tif err := app.appCodec.UnmarshalJSON(evmJSON, &evmGenesis); err != nil {
\t\treturn nil, fmt.Errorf("PRVI native genesis: malformed EVM module: %w", err)
\t}
\tif evmGenesis.Params.EvmDenom != prvicap.BaseDenom {
\t\treturn nil, fmt.Errorf("PRVI native genesis: EVM gas denomination must be aprvi")
\t}
\tstakingJSON, hasStaking := genesisState[stakingtypes.ModuleName]
\tif !hasStaking { return nil, fmt.Errorf("PRVI native genesis: missing staking module") }
\tvar stakingGenesis stakingtypes.GenesisState
\tif err := app.appCodec.UnmarshalJSON(stakingJSON, &stakingGenesis); err != nil {
\t\treturn nil, fmt.Errorf("PRVI native genesis: malformed staking module: %w", err)
\t}
\tif stakingGenesis.Params.BondDenom != prvicap.BaseDenom {
\t\treturn nil, fmt.Errorf("PRVI native genesis: bonded staking denomination must be aprvi")
\t}
\tmintJSON, hasMint := genesisState[minttypes.ModuleName]
\tif !hasMint { return nil, fmt.Errorf("PRVI native genesis: missing mint module") }
\tvar mintGenesis minttypes.GenesisState
\tif err := app.appCodec.UnmarshalJSON(mintJSON, &mintGenesis); err != nil {
\t\treturn nil, fmt.Errorf("PRVI native genesis: malformed mint module: %w", err)
\t}
\tif mintGenesis.Params.MintDenom != prvicap.BaseDenom ||
\t\t!mintGenesis.Params.InflationMin.IsZero() ||
\t\t!mintGenesis.Params.InflationMax.IsZero() ||
\t\t!mintGenesis.Params.InflationRateChange.IsZero() ||
\t\t!mintGenesis.Minter.Inflation.IsZero() ||
\t\t!mintGenesis.Minter.AnnualProvisions.IsZero() {
\t\treturn nil, fmt.Errorf("PRVI native genesis: mint must target aprvi with ZERO inflation and provisions")
\t}
\t// Never inherit upstream permissionless ERC20 registration for a
\t// financial native-denom candidate. No aprvi native/ERC20 conversion
\t// pair is allowed in genesis, even if marked disabled. An upgrade or
\t// governance change could reopen registration: separately review it.
\terc20JSON, hasERC20 := genesisState[erc20types.ModuleName]
\tif !hasERC20 { return nil, fmt.Errorf("PRVI native genesis: missing ERC20 module") }
\tvar erc20Genesis erc20types.GenesisState
\tif err := app.appCodec.UnmarshalJSON(erc20JSON, &erc20Genesis); err != nil {
\t\treturn nil, fmt.Errorf("PRVI native genesis: malformed ERC20 module: %w", err)
\t}
\tif erc20Genesis.Params.PermissionlessRegistration {
\t\treturn nil, fmt.Errorf("PRVI native genesis: permissionless ERC20 registration forbidden")
\t}
\tfor _, pair := range erc20Genesis.TokenPairs {
\t\tif pair.Denom == prvicap.BaseDenom {
\t\t\treturn nil, fmt.Errorf("PRVI native genesis: aprvi ERC20 token pair forbidden")
\t\t}
\t}
\tmetadataValid := false
\tfor _, meta := range bankGenesis.DenomMetadata {
\t\tif meta.Base != prvicap.BaseDenom { continue }
\t\tif metadataValid || meta.Display != "PRVI" {
\t\t\treturn nil, fmt.Errorf("PRVI native genesis: duplicate/invalid aprvi metadata")
\t\t}
\t\tbaseFound, displayFound := false, false
\t\tfor _, unit := range meta.DenomUnits {
\t\t\tif unit.Denom == prvicap.BaseDenom && unit.Exponent == 0 {baseFound = true}
\t\t\tif unit.Denom == "PRVI" && unit.Exponent == 18 {displayFound = true}
\t\t}
\t\tif !baseFound || !displayFound {
\t\t\treturn nil, fmt.Errorf("PRVI native genesis: aprvi requires 18 decimal PRVI metadata")
\t\t}
\t\tmetadataValid = true
\t}
\tif !metadataValid {return nil, fmt.Errorf("PRVI native genesis: missing aprvi/PRVI metadata")}
\t// Only after validating the cap may the upgrade module version map write.
\t// Rejecting the proposed genesis must not touch consensus module stores.
\tif err := app.UpgradeKeeper.SetModuleVersionMap(ctx, app.ModuleManager.GetVersionMap()); err != nil {
\t\treturn nil, fmt.Errorf("PRVI cap: module version map write failed: %w", err)
\t}
\t// Bank GenesisState.Supply is merely a declaration. Its actual minted
\t// supply is checked against the mounted bank state after module InitGenesis.
\tresponse, initErr := app.ModuleManager.InitGenesis(ctx, app.appCodec, genesisState)
\tif initErr != nil { return nil, initErr }
\tif err := app.PriviCapKeeper.InitGenesis(ctx, initialPRVI.String(), app.BankKeeper); err != nil {
\t\treturn nil, fmt.Errorf("PRVI cap genesis initialization denied: %w", err)
\t}
\tif err := app.PriviPoPKeeper.InitGenesis(ctx,popGenesis.ChainID,popGenesis.Authorities); err != nil {
\t\treturn nil,fmt.Errorf("Privi PoP genesis authorization denied: %w",err)
\t}
\tif err := app.CheckPriviNativeERC20Invariant(ctx); err != nil {
\t\treturn nil, fmt.Errorf("PRVI native genesis ERC20 runtime state denied: %w", err)
\t}
\treturn response, nil'''
    app = replace_once(app, old_chainer, new_chainer, "chain init fail-closed proof")
    # Runtime ERC20 safety: reject permissionless registration and any
    # native aprvi mapping on the actual SDK state at both block boundaries.
    # This is defense in depth: it does not atomically forbid every possible
    # in-block transient create/delete route or unreviewed keeper mutation.
    # The per-block token-pair walk requires load/performance testing.
    invariant = '''// CheckPriviNativeERC20Invariant verifies live ERC20 state rather than
// just unsigned genesis declarations. No runtime auto-correction: a
// forbidden state makes block execution fail closed. This is O(token pairs).
func (app *EVMD) CheckPriviNativeERC20Invariant(ctx sdk.Context) error {
\tparams := app.Erc20Keeper.GetParams(ctx)
\tif params.PermissionlessRegistration {
\t\treturn fmt.Errorf("PRVI ERC20 runtime: permissionless registration forbidden")
\t}
\tif app.Erc20Keeper.IsDenomRegistered(ctx, prvicap.BaseDenom) {
\t\treturn fmt.Errorf("PRVI ERC20 runtime: native aprvi denom registry entry forbidden")
\t}
\tfor _, pair := range app.Erc20Keeper.GetTokenPairs(ctx) {
\t\tif pair.Denom == prvicap.BaseDenom {
\t\t\treturn fmt.Errorf("PRVI ERC20 runtime: native aprvi token pair forbidden")
\t\t}
\t}
\treturn nil
}

'''
    app = replace_once(app,
        "func (app *EVMD) BeginBlocker(ctx sdk.Context) (sdk.BeginBlock, error) {",
        invariant + "func (app *EVMD) BeginBlocker(ctx sdk.Context) (sdk.BeginBlock, error) {",
        "inject ERC20 runtime invariant before block entry")
    # Guard supply at block boundaries as defense in depth. This catches
    # unguarded net supply growth above the initial genesis issuance, not a
    # mint-and-burn within one block or an increase below genesis after burns.
    # Whole-system issuance safety still requires exhaustive mint-path audit.
    app = replace_once(app,
        '''func (app *EVMD) BeginBlocker(ctx sdk.Context) (sdk.BeginBlock, error) {
\treturn app.ModuleManager.BeginBlock(ctx)
}'''.replace("\\t", "\t"),
        '''func (app *EVMD) BeginBlocker(ctx sdk.Context) (sdk.BeginBlock, error) {
\tif err := app.PriviPoPKeeper.AssertInitialized(ctx,ctx.ChainID()); err != nil {
\t\treturn sdk.BeginBlock{},fmt.Errorf("Privi PoP beginning-of-block registry denied: %w",err)
\t}
\tif err := app.PriviCapKeeper.Reconcile(ctx, app.BankKeeper); err != nil {
\t\treturn sdk.BeginBlock{}, fmt.Errorf("PRVI beginning-of-block supply check denied: %w", err)
\t}
\tif err := app.CheckPriviNativeERC20Invariant(ctx); err != nil {
\t\treturn sdk.BeginBlock{}, fmt.Errorf("PRVI beginning-of-block ERC20 check denied: %w", err)
\t}
\treturn app.ModuleManager.BeginBlock(ctx)
}'''.replace("\\t", "\t"),
        "pre-block supply invariant")
    app = replace_once(app,
        '''func (app *EVMD) EndBlocker(ctx sdk.Context) (sdk.EndBlock, error) {
\treturn app.ModuleManager.EndBlock(ctx)
}'''.replace("\\t", "\t"),
        '''func (app *EVMD) EndBlocker(ctx sdk.Context) (sdk.EndBlock, error) {
\tresponse, endErr := app.ModuleManager.EndBlock(ctx)
\tif endErr != nil { return response, endErr }
\tif err := app.PriviPoPKeeper.AssertInitialized(ctx,ctx.ChainID()); err != nil {
\t\treturn response,fmt.Errorf("Privi PoP end-of-block registry denied: %w",err)
\t}
\tif err := app.PriviCapKeeper.Reconcile(ctx, app.BankKeeper); err != nil {
\t\treturn response, fmt.Errorf("PRVI end-of-block supply check denied: %w", err)
\t}
\tif err := app.CheckPriviNativeERC20Invariant(ctx); err != nil {
\t\treturn response, fmt.Errorf("PRVI end-of-block ERC20 check denied: %w", err)
\t}
\treturn response, nil
}'''.replace("\\t", "\t"),
        "post-block supply invariant")
    # The upstream SDK PostHandler is empty at v0.54.3. Wrap it rather than
    # mutating EVM balances in an ante handler, which could survive failed
    # execution. Only a successful zero-value EVM call to our dedicated sink
    # triggers authenticated PoP state transitions on FinalizeBlock.
    popPost = '''// ApplyPriviPoPFromFinalizedTx runs in SDK's transaction cache AFTER
// all message execution. Returning an error discards the runMsgs cache.
// CometBFT handles voting; this native app guards PoP position validity.
func (app *EVMD) ApplyPriviPoPFromFinalizedTx(ctx sdk.Context, tx sdk.Tx, simulate, success bool) (sdk.Context, error) {
\tif !success || simulate || ctx.ExecMode()!=sdk.ExecModeFinalize { return ctx,nil }
\tfor _, msg := range tx.GetMsgs() {
\t\teth, ok := msg.(*evmtypes.MsgEthereumTx)
\t\tif !ok { continue }
\t\ttransaction := eth.AsTransaction()
\t\tif transaction == nil { return ctx,fmt.Errorf("Privi PoP EVM transaction missing") }
\t\tto := transaction.To()
\t\tif to == nil || *to != common.HexToAddress(prvipop.PoPSinkEVMAddress) { continue }
\t\tif transaction.Value().Sign()!=0 {return ctx,fmt.Errorf("Privi PoP position tx may not transfer value")}
\t\tif transaction.Gas() > 1000000 {return ctx,fmt.Errorf("Privi PoP position gas limit exceeds test-only bound")}
\t\t// The sink must remain an EOA with no runtime EVM code, making a
\t\t// successful call incapable of hiding a reverted contract execution.
\t\tcodeHash := app.EVMKeeper.GetCodeHash(ctx,*to)
\t\tif len(app.EVMKeeper.GetCode(ctx,codeHash))!=0 {
\t\t\treturn ctx,fmt.Errorf("Privi PoP sink EVM contract code forbidden")
\t\t}
\t\tposition,decodeErr:=prvipop.DecodeEnvelope(transaction.Data())
\t\tif decodeErr!=nil {return ctx,fmt.Errorf("Privi PoP transaction envelope rejected: %w",decodeErr)}
\t\tif _,applyErr:=app.PriviPoPKeeper.Apply(ctx,position);applyErr!=nil {
\t\t\treturn ctx,fmt.Errorf("Privi PoP authenticated native transition denied: %w",applyErr)
\t\t}
\t}
\treturn ctx,nil
}

'''
    app = replace_once(app,
        "func (app *EVMD) setPostHandler() {",
        popPost.replace("\\t","\t") + "func (app *EVMD) setPostHandler() {",
        "attach signed PoP position transaction route to SDK post execution")
    app = replace_once(app,
        "\tapp.SetPostHandler(postHandler)",
        '''\tapp.SetPostHandler(func(ctx sdk.Context, tx sdk.Tx, simulate, success bool) (sdk.Context,error) {
\t\tif postHandler!=nil {
\t\t\tvar err error
\t\t\tctx,err=postHandler(ctx,tx,simulate,success)
\t\t\tif err!=nil {return ctx,err}
\t\t}
\t\treturn app.ApplyPriviPoPFromFinalizedTx(ctx,tx,simulate,success)
\t})'''.replace("\\t","\t"),
        "native PoP post handler installation")
    if app.count("app.ApplyPriviPoPFromFinalizedTx(")!=1:
        raise ValueError("PoP posthandler must be installed exactly once")
    # Fail closed if upstream source evolves to retain or overwrite a raw
    # bank keeper after restricted injection. This static check is intentionally
    # conservative and does NOT replace an audit of module aliases or SDK code.
    # A single unrestricted BaseKeeper constructor exists locally ONLY to be
    # wrapped before the app hands the keeper to other modules.
    if (app.count("bankkeeper.NewBaseKeeper(") != 1 or
            app.count("app.BankKeeper = prvicap.RestrictedBank(") != 1 or
            app.count("app.BankKeeper =") != 1):
        raise ValueError("unaudited bank keeper constructor/assignment; raw bank bypass risk")
    if app.index("app.BankKeeper = prvicap.RestrictedBank(") > app.index(
            "app.ModuleManager.InitGenesis(ctx, app.appCodec, genesisState)"):
        raise ValueError("bank keeper restriction must precede InitGenesis")
    # Verify all modifications before writing anything. No direct on-chain action.
    srcdir = source_repo / "production-network" / "mainnet" / "prvicap"
    required = ["keeper.go", "sdk_bank_adapter.go", "chain_identity.go"]
    files = {}
    for name in required:
        content = (srcdir / name).read_text(encoding="utf-8")
        if "package prvicap" not in content:
            raise ValueError("invalid cap source " + name)
        files[name] = content
    if "func RestrictedBank" not in files["sdk_bank_adapter.go"]:
        raise ValueError("missing bank guard")
    # A helper constant for a dedicated, persistent SDK store, not memory KV.
    files["store.go"] = '''package prvicap

// StoreKey is mounted by the custom app with sdk NewKVStoreKeys, never memstore.
const StoreKey = "prvicap"
'''
    # Validate source before writes to the pinned disposable checkout.
    pop_srcdir = source_repo / "production-network" / "mainnet" / "pop"
    pop_files = {}
    for name in ("position.go", "keeper.go", "wire.go"):
        content = (pop_srcdir / name).read_text(encoding="utf-8")
        if "package position" not in content:
            raise ValueError("invalid native PoP source " + name)
        pop_files[name] = content
    if (upstream / "evmd" / "prvipop").exists():
        raise ValueError("refusing to overwrite PoP consensus source")
    if app.count("app.PriviPoPKeeper = popKeeper") != 1 or app.count(
            "app.PriviPoPKeeper.InitGenesis(ctx,popGenesis.ChainID,popGenesis.Authorities)") != 1:
        raise ValueError("PoP keeper must mount and initialize once")
    if (upstream / "evmd" / "prvicap").exists():
        raise ValueError("refusing to overwrite cap keeper source")
    dest = upstream / "evmd" / "prvicap"
    dest.mkdir()
    for name, content in files.items():
        (dest / name).write_text(content, encoding="utf-8")
    pop_dest = upstream / "evmd" / "prvipop"
    pop_dest.mkdir()
    for name, content in pop_files.items():
        (pop_dest / name).write_text(content, encoding="utf-8")
    app_path.write_text(app, encoding="utf-8")
    return {
        "status": "BUILD_ONLY_PRVI_CONSENSUS_CAP_APP_SOURCE_WIRED",
        "upstream": UPSTREAM_COMMIT,
        "app_sha256": hashlib.sha256(app.encode("utf-8")).hexdigest(),
        "cap_source_files": sorted(files),
        "pop_source_files": sorted(pop_files),
        "financial_mainnet": "NOT_ACTIVE",
        "release_ready": False,
        "limitations": "Compiler proof only; no financial genesis, validators, production audits or real PRVI issued",
    }

def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--upstream", required=True, type=Path)
    ap.add_argument("--source-repo", required=True, type=Path)
    args = ap.parse_args()
    import json
    print(json.dumps(apply_patch(args.upstream, args.source_repo), indent=2))

if __name__ == "__main__":
    main()
