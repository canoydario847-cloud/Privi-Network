#!/usr/bin/env python3
"""Fail-closed, source-pinned *build-only* prototype wiring for PRVI cap keeper.

Clones are disposable test workspace copies of cosmos/evm v0.7.3. Never run
on an operating blockchain or production software tree. No genesis or keys
are generated by this script; no financial PRVI is created.
"""
import argparse
import hashlib
import shutil
import subprocess
from pathlib import Path

TAG = "v0.7.3"
UPSTREAM_COMMIT = "c3ae9067a7eadcdea55a5192226916deb44c71c4"

def replace_once(content, old, new, name):
    if content.count(old) != 1:
        raise ValueError("pinned upstream mismatch at %s (expected one occurrence, found %d)"
                         % (name, content.count(old)))
    return content.replace(old, new)

def apply_patch(upstream, source_repo, *, verify_git=True):
    upstream = Path(upstream).resolve(strict=True)
    source_repo = Path(source_repo).resolve(strict=True)
    if not upstream.is_dir() or upstream.name != ".upstream-capbuild":
        raise ValueError("refusing non-disposable upstream checkout")
    if verify_git:
        tag = subprocess.check_output(["git", "-C", str(upstream), "describe",
                                       "--tags", "--exact-match"], text=True).strip()
        commit = subprocess.check_output(["git", "-C", str(upstream),
                                          "rev-parse", "HEAD"], text=True).strip()
        if (tag, commit) != (TAG, UPSTREAM_COMMIT):
            raise ValueError("upstream must be exact reviewed v0.7.3 commit")
        if subprocess.check_output(["git", "-C", str(upstream), "status",
                                    "--porcelain"], text=True).strip():
            raise ValueError("upstream checkout must be clean")
    app_path = upstream / "evmd" / "app.go"
    app = app_path.read_text(encoding="utf-8")
    app = replace_once(app,
        'evmconfig "github.com/cosmos/evm/evmd/config"',
        'evmconfig "github.com/cosmos/evm/evmd/config"\n'
        '\tprvicap "github.com/cosmos/evm/evmd/prvicap"',
        "cap import")
    # The upstream Cosmos EVM demo chain ID must not be accepted by the
    # PRVI-customized binary, even when a future genesis declares PRVI.
    # Numeric uniqueness and the operator-approved production identity remain
    # separate launch gates: this filter is necessary, not sufficient.
    app = replace_once(app,
        "\tevmChainID := cast.ToUint64(appOpts.Get(srvflags.EVMChainID))\n\tencodingConfig := evmencoding.MakeConfig(evmChainID)",
        "\tevmChainID := cast.ToUint64(appOpts.Get(srvflags.EVMChainID))\n"
        "\tif err := prvicap.ValidateEVMChainID(evmChainID); err != nil {\n"
        "\t\tpanic(fmt.Errorf(\"PRVI EVM chain identity rejected: %w\", err))\n"
        "\t}\n"
        "\tencodingConfig := evmencoding.MakeConfig(evmChainID)",
        "validate EVM chain identity before any bank or EVM keeper")
    app = replace_once(app,
        "\tBankKeeper            bankkeeper.Keeper",
        "\tBankKeeper            bankkeeper.Keeper\n\tPriviCapKeeper        prvicap.Keeper",
        "cap keeper field")
    app = replace_once(app,
        "\t\tauthtypes.StoreKey, banktypes.StoreKey, stakingtypes.StoreKey,",
        "\t\tauthtypes.StoreKey, banktypes.StoreKey, stakingtypes.StoreKey,\n"
        "\t\tprvicap.StoreKey,",
        "mount dedicated merkle KV state")
    old_bank = '''\tapp.BankKeeper = bankkeeper.NewBaseKeeper(
\t\tappCodec,
\t\truntime.NewKVStoreService(keys[banktypes.StoreKey]),
\t\tapp.AccountKeeper,
\t\tevmconfig.BlockedAddresses(),
\t\tauthAddr,
\t\tlogger,
\t)
\tapp.BankKeeper = app.BankKeeper.WithObjStoreKey(oKeys[banktypes.ObjectStoreKey])'''
    new_bank = '''\t// CRITICAL: No module may receive an unrestricted bank keeper copy.
\t// There is no financial genesis, key, or issued PRVI in this build-only prototype.
\tpriviCap, capErr := prvicap.New(runtime.NewKVStoreService(keys[prvicap.StoreKey]))
\tif capErr != nil { panic(capErr) }
\tapp.PriviCapKeeper = priviCap
\tbaseBank := bankkeeper.NewBaseKeeper(
\t\tappCodec,
\t\truntime.NewKVStoreService(keys[banktypes.StoreKey]),
\t\tapp.AccountKeeper,
\t\tevmconfig.BlockedAddresses(),
\t\tauthAddr,
\t\tlogger,
\t)
\tbaseBank = baseBank.WithObjStoreKey(oKeys[banktypes.ObjectStoreKey])
\tapp.BankKeeper = prvicap.RestrictedBank(baseBank, app.PriviCapKeeper)'''
    app = replace_once(app, old_bank, new_bank, "apply restriction before bank injection")
    # Cosmos SDK v0.54.3 x/bank migration registration currently requires a
    # concrete BaseKeeper. The only exception receives a mint-restricted copy;
    # all other modules receive the sealed direct-balance-denying interface.
    # The residual raw keeper reference remains a financial launch blocker.
    app = replace_once(app,
        "bank.NewAppModule(appCodec, app.BankKeeper, app.AccountKeeper, nil)",
        "bank.NewAppModule(appCodec,\n"
        "\t\t\tbaseBank.WithMintCoinsRestriction(app.PriviCapKeeper.MintRestriction),\n"
        "\t\t\tapp.AccountKeeper, nil)",
        "SDK bank migration concrete keeper with native mint restriction")
    if app.count("baseBank.WithMintCoinsRestriction(app.PriviCapKeeper.MintRestriction)") != 1:
        raise ValueError("raw bank migration exception must be unique")
    if app.count("app.BankKeeper = prvicap.RestrictedBank(baseBank, app.PriviCapKeeper)") != 1:
        raise ValueError("only one guarded module-facing bank injection allowed")
    # Upstream writes the upgrade module version map before calling InitGenesis.
    # Move it after all native PRVI genesis policy checks so rejected
    # financial genesis cannot cause even preliminary consensus KV writes.
    app = replace_once(app,
        "\tif err := app.UpgradeKeeper.SetModuleVersionMap(ctx, app.ModuleManager.GetVersionMap()); err != nil {\n"
        "\t\tpanic(err)\n"
        "\t}\n\n",
        "",
        "defer upgrade version-map write until after PRVI genesis preflight")
    old_chainer = '\treturn app.ModuleManager.InitGenesis(ctx, app.appCodec, genesisState)'
    new_chainer = '''\t// The bank supply is loaded by module initialization. Require its exact
\t// declared native PRVI genesis supply, refusing default upstream TEST genesis.
\t// PRVI minting remains forbidden before and after keeper InitGenesis.
\t// Reject invalid declared native issuance before touching module state.
\tbankJSON, found := genesisState[banktypes.ModuleName]
\tif !found { return nil, fmt.Errorf("PRVI cap: bank genesis absent") }
\tvar bankGenesis banktypes.GenesisState
\tif err := app.appCodec.UnmarshalJSON(bankJSON, &bankGenesis); err != nil {
\t\treturn nil, fmt.Errorf("PRVI cap: invalid bank genesis: %w", err)
\t}
\t// Validate the complete bank genesis before any module writes. This
\t// rejects malformed balances, duplicate entries and other denom errors
\t// rather than checking only the aprvi allocation sum below.
\tif err := bankGenesis.Validate(); err != nil {
\t\treturn nil, fmt.Errorf("PRVI pre-init bank genesis rejected: %w", err)
\t}
\tinitialPRVI := bankGenesis.Supply.AmountOf(prvicap.BaseDenom)
\tif err := prvicap.ValidateGenesisBase(initialPRVI.String()); err != nil {
\t\treturn nil, fmt.Errorf("PRVI pre-init genesis supply rejected: %w", err)
\t}
\t// Check native genesis allocations BEFORE any module InitGenesis writes.
\t// SDK bank InitGenesis also checks conservation, but runs after other
\t// modules may already have changed their state. This is a preflight only.
\tnativeBalanceTotal := initialPRVI.Sub(initialPRVI)
\tfor _, account := range bankGenesis.Balances {
\t\tamount := account.Coins.AmountOf(prvicap.BaseDenom)
\t\tif amount.IsNegative() {
\t\t\treturn nil, fmt.Errorf("PRVI native genesis: negative aprvi account balance")
\t\t}
\t\tnativeBalanceTotal = nativeBalanceTotal.Add(amount)
\t\tif nativeBalanceTotal.GT(initialPRVI) {
\t\t\treturn nil, fmt.Errorf("PRVI native genesis: aprvi balances exceed supply")
\t\t}
\t}
\tif !nativeBalanceTotal.Equal(initialPRVI) {
\t\treturn nil, fmt.Errorf("PRVI native genesis: aprvi account balances do not match supply")
\t}
\t// Native PRVI must actually be the EVM gas and staking denomination.
\t// Do not allow a misleading genesis with capped aprvi but fees/stake in
\t// upstream stake/atest. All checks precede consensus module writes.
\tevmJSON, hasEVM := genesisState[evmtypes.ModuleName]
\tif !hasEVM { return nil, fmt.Errorf("PRVI native genesis: missing EVM module") }
\tvar evmGenesis evmtypes.GenesisState
\tif err := app.appCodec.UnmarshalJSON(evmJSON, &evmGenesis); err != nil {
\t\treturn nil, fmt.Errorf("PRVI native genesis: malformed EVM module: %w", err)
\t}
\tif evmGenesis.Params.EvmDenom != prvicap.BaseDenom {
\t\treturn nil, fmt.Errorf("PRVI native genesis: EVM gas denomination must be aprvi")
\t}
\tstakingJSON, hasStaking := genesisState[stakingtypes.ModuleName]
\tif !hasStaking { return nil, fmt.Errorf("PRVI native genesis: missing staking module") }
\tvar stakingGenesis stakingtypes.GenesisState
\tif err := app.appCodec.UnmarshalJSON(stakingJSON, &stakingGenesis); err != nil {
\t\treturn nil, fmt.Errorf("PRVI native genesis: malformed staking module: %w", err)
\t}
\tif stakingGenesis.Params.BondDenom != prvicap.BaseDenom {
\t\treturn nil, fmt.Errorf("PRVI native genesis: bonded staking denomination must be aprvi")
\t}
\tmintJSON, hasMint := genesisState[minttypes.ModuleName]
\tif !hasMint { return nil, fmt.Errorf("PRVI native genesis: missing mint module") }
\tvar mintGenesis minttypes.GenesisState
\tif err := app.appCodec.UnmarshalJSON(mintJSON, &mintGenesis); err != nil {
\t\treturn nil, fmt.Errorf("PRVI native genesis: malformed mint module: %w", err)
\t}
\tif mintGenesis.Params.MintDenom != prvicap.BaseDenom ||
\t\t!mintGenesis.Params.InflationMin.IsZero() ||
\t\t!mintGenesis.Params.InflationMax.IsZero() ||
\t\t!mintGenesis.Params.InflationRateChange.IsZero() ||
\t\t!mintGenesis.Minter.Inflation.IsZero() ||
\t\t!mintGenesis.Minter.AnnualProvisions.IsZero() {
\t\treturn nil, fmt.Errorf("PRVI native genesis: mint must target aprvi with ZERO inflation and provisions")
\t}
\t// Never inherit upstream permissionless ERC20 registration for a
\t// financial native-denom candidate. No aprvi native/ERC20 conversion
\t// pair is allowed in genesis, even if marked disabled. An upgrade or
\t// governance change could reopen registration: separately review it.
\terc20JSON, hasERC20 := genesisState[erc20types.ModuleName]
\tif !hasERC20 { return nil, fmt.Errorf("PRVI native genesis: missing ERC20 module") }
\tvar erc20Genesis erc20types.GenesisState
\tif err := app.appCodec.UnmarshalJSON(erc20JSON, &erc20Genesis); err != nil {
\t\treturn nil, fmt.Errorf("PRVI native genesis: malformed ERC20 module: %w", err)
\t}
\tif erc20Genesis.Params.PermissionlessRegistration {
\t\treturn nil, fmt.Errorf("PRVI native genesis: permissionless ERC20 registration forbidden")
\t}
\tfor _, pair := range erc20Genesis.TokenPairs {
\t\tif pair.Denom == prvicap.BaseDenom {
\t\t\treturn nil, fmt.Errorf("PRVI native genesis: aprvi ERC20 token pair forbidden")
\t\t}
\t}
\tmetadataValid := false
\tfor _, meta := range bankGenesis.DenomMetadata {
\t\tif meta.Base != prvicap.BaseDenom { continue }
\t\tif metadataValid || meta.Display != "PRVI" {
\t\t\treturn nil, fmt.Errorf("PRVI native genesis: duplicate/invalid aprvi metadata")
\t\t}
\t\tbaseFound, displayFound := false, false
\t\tfor _, unit := range meta.DenomUnits {
\t\t\tif unit.Denom == prvicap.BaseDenom && unit.Exponent == 0 {baseFound = true}
\t\t\tif unit.Denom == "PRVI" && unit.Exponent == 18 {displayFound = true}
\t\t}
\t\tif !baseFound || !displayFound {
\t\t\treturn nil, fmt.Errorf("PRVI native genesis: aprvi requires 18 decimal PRVI metadata")
\t\t}
\t\tmetadataValid = true
\t}
\tif !metadataValid {return nil, fmt.Errorf("PRVI native genesis: missing aprvi/PRVI metadata")}
\t// Only after all native asset identity checks may consensus module writes begin.\n\tif err := app.UpgradeKeeper.SetModuleVersionMap(ctx, app.ModuleManager.GetVersionMap()); err != nil {\n\t\treturn nil, fmt.Errorf("PRVI genesis: upgrade version map: %w", err)\n\t}\n\tresponse, initErr := app.ModuleManager.InitGenesis(ctx, app.appCodec, genesisState)
\tif initErr != nil { return nil, initErr }
\tif err := app.PriviCapKeeper.InitGenesis(ctx, initialPRVI.String(), app.BankKeeper); err != nil {
\t\treturn nil, fmt.Errorf("PRVI cap genesis initialization denied: %w", err)
\t}
\treturn response, nil'''
    app = replace_once(app, old_chainer, new_chainer, "chain init fail-closed proof")
    # Defense in depth, build-only: re-check actual live consensus state at
    # block boundaries, not merely unsigned genesis declarations. This is
    # NOT an atomic bank mutation boundary. Account scans are O(accounts)
    # and ERC20 registry scans O(pairs): benchmark before financial use.
    invariant = '''// CheckPriviNativeRuntimeInvariant checks mounted SDK module state at
// block boundaries. It does not prevent transient, same-block violations.
func (app *EVMD) CheckPriviNativeRuntimeInvariant(ctx sdk.Context) error {
	evmp := app.EVMKeeper.GetParams(ctx)
	if evmp.EvmDenom != prvicap.BaseDenom {
		return fmt.Errorf("PRVI runtime: EVM gas denom must be aprvi")
	}
	bond, err := app.StakingKeeper.BondDenom(ctx)
	if err != nil { return fmt.Errorf("PRVI runtime: staking params: %w", err) }
	if bond != prvicap.BaseDenom {
		return fmt.Errorf("PRVI runtime: staking bond denom must be aprvi")
	}
	mintp, err := app.MintKeeper.Params.Get(ctx)
	if err != nil { return fmt.Errorf("PRVI runtime: mint params: %w", err) }
	minter, err := app.MintKeeper.Minter.Get(ctx)
	if err != nil { return fmt.Errorf("PRVI runtime: mint state: %w", err) }
	if mintp.MintDenom != prvicap.BaseDenom ||
		!mintp.InflationMin.IsZero() || !mintp.InflationMax.IsZero() ||
		!mintp.InflationRateChange.IsZero() ||
		!minter.Inflation.IsZero() || !minter.AnnualProvisions.IsZero() {
		return fmt.Errorf("PRVI runtime: native mint must have zero inflation")
	}
	erc20p := app.Erc20Keeper.GetParams(ctx)
	if erc20p.PermissionlessRegistration {
		return fmt.Errorf("PRVI runtime: ERC20 permissionless registration forbidden")
	}
	if app.Erc20Keeper.IsDenomRegistered(ctx, prvicap.BaseDenom) {
		return fmt.Errorf("PRVI runtime: aprvi ERC20 denom registration forbidden")
	}
	for _, pair := range app.Erc20Keeper.GetTokenPairs(ctx) {
		if pair.Denom == prvicap.BaseDenom {
			return fmt.Errorf("PRVI runtime: aprvi ERC20 token pair forbidden")
		}
	}
	return nil
}

'''
    app = replace_once(app,
        "func (app *EVMD) BeginBlocker(ctx sdk.Context) (sdk.BeginBlock, error) {",
        invariant + "func (app *EVMD) BeginBlocker(ctx sdk.Context) (sdk.BeginBlock, error) {",
        "mount native runtime denomination and ERC20 checks")
    app = replace_once(app,
        '''func (app *EVMD) BeginBlocker(ctx sdk.Context) (sdk.BeginBlock, error) {
\treturn app.ModuleManager.BeginBlock(ctx)
}''',
        '''func (app *EVMD) BeginBlocker(ctx sdk.Context) (sdk.BeginBlock, error) {
\tif err := app.PriviCapKeeper.Reconcile(ctx, app.BankKeeper); err != nil {
\t\treturn sdk.BeginBlock{}, fmt.Errorf("PRVI begin-block supply check: %w", err)
\t}
\tif err := app.CheckPriviNativeRuntimeInvariant(ctx); err != nil {
\t\treturn sdk.BeginBlock{}, fmt.Errorf("PRVI begin-block runtime invariant: %w", err)
\t}
\treturn app.ModuleManager.BeginBlock(ctx)
}''',
        "fail closed before bank and module BeginBlock")
    app = replace_once(app,
        '''func (app *EVMD) EndBlocker(ctx sdk.Context) (sdk.EndBlock, error) {
\treturn app.ModuleManager.EndBlock(ctx)
}''',
        '''func (app *EVMD) EndBlocker(ctx sdk.Context) (sdk.EndBlock, error) {
\tresponse, err := app.ModuleManager.EndBlock(ctx)
\tif err != nil { return response, err }
\tif err := app.PriviCapKeeper.Reconcile(ctx, app.BankKeeper); err != nil {
\t\treturn response, fmt.Errorf("PRVI end-block supply check: %w", err)
\t}
\tif err := app.CheckPriviNativeRuntimeInvariant(ctx); err != nil {
\t\treturn response, fmt.Errorf("PRVI end-block runtime invariant: %w", err)
\t}
\treturn response, nil
}''',
        "fail closed after bank and module EndBlock")
    # Verify all modifications before writing anything. No direct on-chain action.
    srcdir = source_repo / "production-network" / "mainnet" / "prvicap"
    required = ["keeper.go", "sdk_bank_adapter.go", "chain_identity.go"]
    files = {}
    for name in required:
        content = (srcdir / name).read_text(encoding="utf-8")
        if "package prvicap" not in content:
            raise ValueError("invalid cap source " + name)
        files[name] = content
    if "func RestrictedBank" not in files["sdk_bank_adapter.go"]:
        raise ValueError("missing bank guard")
    if "func ValidateEVMChainID" not in files["chain_identity.go"]:
        raise ValueError("missing chain identity guard")
    # A helper constant for a dedicated, persistent SDK store, not memory KV.
    files["store.go"] = '''package prvicap

// StoreKey is mounted by the custom app with sdk NewKVStoreKeys, never memstore.
const StoreKey = "prvicap"
'''
    if (upstream / "evmd" / "prvicap").exists():
        raise ValueError("refusing to overwrite cap keeper source")
    dest = upstream / "evmd" / "prvicap"
    dest.mkdir()
    for name, content in files.items():
        (dest / name).write_text(content, encoding="utf-8")
    app_path.write_text(app, encoding="utf-8")
    return {
        "status": "BUILD_ONLY_PRVI_CONSENSUS_CAP_APP_SOURCE_WIRED",
        "upstream": UPSTREAM_COMMIT,
        "app_sha256": hashlib.sha256(app.encode("utf-8")).hexdigest(),
        "cap_source_files": sorted(files),
        "financial_mainnet": "NOT_ACTIVE",
        "release_ready": False,
        "limitations": "Compiler proof only; no financial genesis, validators, production audits or real PRVI issued",
    }

def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--upstream", required=True, type=Path)
    ap.add_argument("--source-repo", required=True, type=Path)
    args = ap.parse_args()
    import json
    print(json.dumps(apply_patch(args.upstream, args.source_repo), indent=2))

if __name__ == "__main__":
    main()
